internal fun CategoryEntity.displayLabel(resources: Resources): String =
    if (isSystem && name == (defaultName ?: name)) localizedName(name, resources) else name

internal fun SubcategoryEntity.displayLabel(resources: Resources): String =
    if (isSystem && name == (defaultName ?: name)) localizedName(name, resources) else name

internal fun CategoryEntity.displayDescription(resources: Resources): String =
    if (isSystem && description == defaultDescription) {
        builtinDescriptions[defaultName ?: name]?.let(resources::getString) ?: description
    } else description

